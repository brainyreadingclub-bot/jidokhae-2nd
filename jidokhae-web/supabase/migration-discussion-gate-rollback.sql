-- ============================================================
-- 토론모임 격리 플래그 (A-3) — Rollback
--
-- 🔴 **먼저 읽을 것: 대부분의 경우 이 파일을 실행할 이유가 없다.**
--
--   토론모임을 내리고 싶은 것이라면 행을 지우지 말고 값만 바꾼다:
--
--     UPDATE public.site_settings SET value = 'off', updated_at = now()
--      WHERE key = 'discussion_meeting_enabled';
--
--   행을 지우는 것과 'off'로 두는 것은 코드 동작이 같다(둘 다 OFF).
--   다른 점은 하나 — 행이 없으면 **다시 켤 때 INSERT를 새로 써야 한다.**
--   사고 시간에 SQL을 쓰게 만들지 않으려고 행을 만들어 둔 것이므로, 지우면 그 장치가 사라진다.
--
-- 아래 DELETE는 코드까지 revert해서 이 키가 아예 없던 상태로 되돌릴 때만 쓴다.
--
-- ⚠️ 돈은 이 SQL로 움직이지 않는다. 플래그는 화면을 내릴 뿐 모임을 취소하지 않는다.
--    진행 중인 토론모임 자체를 취소해야 하면 기존 모임 삭제 경로(100% 환불,
--    /api/meetings/[id]/delete)를 쓴다. 새 경로를 만들지 않는다.
-- ============================================================

DELETE FROM public.site_settings WHERE key = 'discussion_meeting_enabled';
