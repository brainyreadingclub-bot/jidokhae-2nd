/**
 * UserPromptSubmit 훅 — 대표님께 답하기 직전에 「보고 계약」을 끼워 넣는다.
 *
 * 왜 이게 필요한가
 *   같은 지시를 **네 번** 받았다 — 2026-08-18 · 09-19 · 09-22 · 10-06.
 *   그때마다 메모리(`feedback_brief_reports.md`)에 적었고, 네 번 다 안 지켜졌다.
 *   메모리는 세션 **시작**에 한 번 들어오고 대화가 길어지면 뒤로 밀린다.
 *   보고를 쓰는 순간에는 이미 눈앞에 없다.
 *
 *   그래서 적어두는 대신 **매 턴, 답을 쓰기 직전에** 올린다.
 *   `inject-decisions.mjs`가 "찾아 읽으라" 대신 "눈앞에 둔다"로 푼 것과 같은 방식이다.
 *
 * 왜 길이가 아니라 「무엇을 넣느냐」인가
 *   2026-10-06 대표님: *"내가 다시 알 필요 없는 건 보고하지 마."*
 *   짧게 쓰려고 줄만 줄이면 핵심이 같이 잘린다. 자를 것은 길이가 아니라
 *   **대표님이 손댈 일이 없는 내용**이다 — 통과한 검증, 내가 이미 고친 것,
 *   경위, 사과. 그 셋을 빼면 길이는 저절로 줄어든다.
 *
 * 적응 — 대표님이 상세를 요청하면 계약을 풀어준다
 *   "자세히" "상세" "왜" "근거" 같은 말이 있으면 압축 규칙 대신
 *   **상세가 허용됐다**는 한 줄을 넣는다. 안 그러면 물어도 짧게만 답하게 된다.
 *
 * 출력
 *   stdout에 JSON 한 덩어리. 실패하면 아무것도 내지 않고 조용히 끝낸다 —
 *   훅이 대화를 막으면 안 된다.
 */

const 압축 = [
  '[보고 규칙 — 대표님은 비전공자다]',
  '',
  '## 결정 필요',
  '',
  '대표님이 답해야 할 것만, 최대 3개. 각 항목 세 줄 —',
  '질문(예/아니오 또는 A/B로 답할 수 있게) / 권고와 이유 / 안 정하면 무슨 일이 생기는지.',
  '없으면 「결정할 것 없음」 한 줄만 쓴다.',
  '',
  '돈·회원 데이터·배포처럼 되돌릴 수 없는 일이 걸려 있으면',
  '결정 필요보다 위에 따로 적는다.',
  '',
  '## 한 일',
  '',
  '3줄 이내. 결과만 쓰고 과정은 쓰지 않는다.',
  '',
  '## 쓰지 않는 것',
  '',
  '파일명·PR 번호·커밋 번호·전문용어. 꼭 필요하면 괄호로 쉬운 말을 붙인다.',
  '표와 이모지. 전체 15줄 이내.',
  '',
  '근거와 상세는 대표님이 「자세히」라고 할 때만 낸다.',
  '질문하기 전에 DECISIONS.md와 할 일 목록에 이미 답이 있는지 먼저 확인한다.',
].join('\n')

const 상세허용 = [
  '[보고 규칙 — 이번 턴은 상세가 허용됐다]',
  '',
  '「자세히」를 요청하셨다. 15줄 제한과 근거 금지를 푼다. 결론은 맨 위에 둔다.',
  '그래도 유지하는 것 셋 — 표·이모지 금지 / 「결정 필요」가 맨 위 /',
  '되돌릴 수 없는 일은 그보다 위.',
].join('\n')

// 낱말을 「자세히」 하나로 줄였다 (2026-10-07 대표님 지시).
// 전에는 13개였고 그중 '전부'·'보고서'·'정리해줘' 때문에 압축 규칙이 자주 풀렸다.
const 상세요청 = /자세히/

try {
  const 입력 = await new Promise((resolve) => {
    let buf = ''
    process.stdin.setEncoding('utf8')
    process.stdin.on('data', (c) => (buf += c))
    process.stdin.on('end', () => resolve(buf))
    setTimeout(() => resolve(buf), 2000)
  })

  const prompt = (JSON.parse(입력 || '{}').prompt ?? '').toString()

  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'UserPromptSubmit',
        additionalContext: 상세요청.test(prompt) ? 상세허용 : 압축,
      },
      suppressOutput: true,
    }),
  )
} catch {
  // 조용히 끝낸다. 보고 규칙 때문에 대화가 막히면 그게 더 나쁘다.
}
